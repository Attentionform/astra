/**
 * Builds the template files. Usage: build <outDir>. Output is deterministic: the same sources give the same bytes.
 */
import * as fs from 'fs';
import * as path from 'path';
import { report } from './report';
import { blank, invoice, letter, manuscript, memo, newsletter, proposal, researchPaper, technicalSpec } from './others';
import { A4, LETTER, type PageSetup } from './lib';
import { DESIGN_VERSION } from './themes';
import AdmZip from '../../src/adm-zip-safe';
import { DOMParser } from '../../src/ooxml/dom-parser';
import { findRegion, findSlot, hashNodes } from '../../src/compose/template-canonical';

const out = process.argv[2];
const manifestPath = process.argv[3];
if (!out) throw new Error('usage: build <outDir> [manifest.ts]');
fs.mkdirSync(out, { recursive: true });
const builders: Record<string, (page: PageSetup) => Buffer> = {
  blank, report, memo, letter, proposal, invoice,
  'technical-spec': technicalSpec, 'research-paper': researchPaper, novel: manuscript, newsletter,
};
// Letter is the default; the A4 variant has the same design on A4 paper.
const manifest: Record<string, { region: string[]; slots: Record<string, string> }> = {};

/** Expected hashes of the placeholder body and the title slot of one built file. */
function measure(buf: Buffer, name: string): { region: string; slots: Record<string, string> } | null {
  const xml = new AdmZip(buf).readAsText('word/document.xml');
  const doc = new DOMParser().parseFromString(xml, 'text/xml');
  const body = doc.getElementsByTagName('w:body')[0];
  const region = findRegion(body);
  if (!region) return null;
  const slots: Record<string, string> = {};
  const title = findSlot(body, 'title');
  if (title) slots.title = hashNodes(title.nodes);
  if (region.nodes.length === 0) throw new Error(`${name}: empty region`);
  return { region: hashNodes(region.nodes), slots };
}

for (const [name, build] of Object.entries(builders)) {
  const letter = build(LETTER);
  const a4 = build(A4);
  fs.writeFileSync(path.join(out, `${name}.docx`), letter);
  fs.writeFileSync(path.join(out, `${name}.a4.docx`), a4);
  const m = measure(letter, name);
  const mA4 = measure(a4, name);
  if (m && mA4) {
    // Table widths follow the page width, so the body may differ between paper sizes: both hashes are valid. The slot must not.
    if (JSON.stringify(m.slots) !== JSON.stringify(mA4.slots)) throw new Error(`${name}: Letter and A4 slots differ`);
    manifest[`${name}@${DESIGN_VERSION}`] = { region: [...new Set([m.region, mA4.region])], slots: m.slots };
  }
  console.log(`built ${name}.docx and ${name}.a4.docx${m ? '' : ' (no placeholder body)'}`);
}
if (manifestPath) {
  const entries = Object.entries(manifest).sort(([a], [b]) => (a < b ? -1 : 1));
  const lines = entries.map(([k, v]) => `  '${k}': { region: ${JSON.stringify(v.region)}, slots: ${JSON.stringify(v.slots)} },`);
  fs.writeFileSync(
    manifestPath,
    `// Generated by packages/engine/scripts/templates/build.ts (npm run build:templates). Do not edit.\n` +
      `// The expected hashes of each template's placeholder body (one per paper size) and title slot. Compose replaces a body only when it still matches.\n` +
      `export const TEMPLATE_MANIFEST: Record<string, { region: string[]; slots: Record<string, string> }> = {\n${lines.join('\n')}\n};\n`
  );
}
